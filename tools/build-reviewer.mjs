async function packageDirectory(name, fromDirectory) {
  let current = fromDirectory;
  const rootPath = parse(current).root;
  while (current !== rootPath) {
    const directory = join(current, "node_modules", ...name.split("/"));
    try {
      const packageJson = JSON.parse(await readFile(join(directory, "package.json"), "utf8"));
      if (packageJson.name === name) return { directory, packageJson };
    } catch (error) {
      if (error?.code !== "ENOENT") throw error;
    }
    current = dirname(current);
  }
  throw new Error(`Could not locate package metadata for ${name} from ${fromDirectory}.`);
}

async function collectRuntimePackages() {
  const pending = [
    { name: "@pierre/diffs", fromDirectory: root },
    { name: "markdown-it", fromDirectory: root },
  ];
  const packages = new Map();
  while (pending.length > 0) {
    const request = pending.shift();
    const resolvedPackage = await packageDirectory(request.name, request.fromDirectory);
    const key = `${resolvedPackage.packageJson.name}@${resolvedPackage.packageJson.version}`;
    if (packages.has(key)) continue;
    packages.set(key, resolvedPackage);
    for (const dependency of Object.keys(resolvedPackage.packageJson.dependencies ?? {})) {
      pending.push({ name: dependency, fromDirectory: resolvedPackage.directory });
    }
  }
  return [...packages.entries()].sort(([left], [right]) => left.localeCompare(right));
}

async function findLicense(directory) {
  const files = await readdir(directory);
  const license = files
    .filter((file) => /^(?:license|licence|copying)(?:\..+)?$/i.test(file))
    .sort((left, right) => left.localeCompare(right))[0];
  return license ? (await readFile(join(directory, license), "utf8")).trim() : null;
}

async function buildNotices() {
  const packages = await collectRuntimePackages();
  const sections = [
    "# Third-party notices",
    "",
    "The embedded review workspace bundles the packages below. This file is generated by `tools/build-reviewer.mjs`.",
  ];
  for (const [key, { directory, packageJson }] of packages) {
    const licenseText = await findLicense(directory);
    sections.push(
      "",
      `## ${key}`,
      "",
      `Declared license: ${packageJson.license ?? "not declared"}`,
      "",
      licenseText ?? "The published package did not include a standalone license file.",
    );
  }
  return `${sections.join("\n")}\n`;
}

const notices = await buildNotices();
for (const skillDirectory of skillDirectories) {
  const assetDirectory = join(skillDirectory, "assets");
  const scriptDirectory = join(skillDirectory, "scripts");
  const licenseDirectory = join(skillDirectory, "licenses");
  await rm(assetDirectory, { recursive: true, force: true });
  await rm(scriptDirectory, { recursive: true, force: true });
  await rm(licenseDirectory, { recursive: true, force: true });
  await mkdir(assetDirectory, { recursive: true });
  await mkdir(scriptDirectory, { recursive: true });
  await mkdir(licenseDirectory, { recursive: true });
  await cp(outputDirectory, assetDirectory, { recursive: true });
  await cp(join(sourceDirectory, "runtime.mjs"), join(scriptDirectory, "review-workspace.mjs"));
  await cp(join(sourceDirectory, "licenses"), licenseDirectory, { recursive: true });
  await writeFile(join(licenseDirectory, "THIRD_PARTY_NOTICES.md"), notices);
}
